export function svgInner(raw: string): string {
  return raw.replace(/^[\s\S]*?<svg[^>]*>/i, '').replace(/<\/svg>[\s\S]*$/i, '')
}

export function groupInner(raw: string, id: string): string {
  const open = `<g id="${id}">`
  const start = raw.indexOf(open) + open.length
  return raw.slice(start, raw.indexOf('</g>', start))
}

export function svgGroupIds(raw: string): string[] {
  return [...raw.matchAll(/<g id="([^"]+)"/g)].map(m => m[1]!)
}

export function svgViewBox(raw: string): string {
  const found = /viewBox="([^"]+)"/.exec(raw)
  if (found === null) throw new Error('viewBox')
  return found[1]!
}

function stageOnly(raw: string, stage: string): string {
  const body = svgInner(raw)
  return body.replace(/<g id="([^"]+)"/g, (_m, id: string) =>
    id === stage ? `<g id="${id}"` : `<g id="${id}" display="none"`,
  )
}

const SVG_NS = 'http://www.w3.org/2000/svg'
const SYM_IDS = new Map<string, string>()
const SYM_QUEUE: { id: string; html: string }[] = []
let symSeq = 0
let symAcc: SVGGElement | undefined

function symAdopt(id: string, html: string): void {
  if (symAcc === undefined) {
    SYM_QUEUE.push({ id, html })
    return
  }
  const g = document.createElementNS(SVG_NS, 'g')
  g.id = id
  g.innerHTML = html
  symAcc.appendChild(g)
}

export function symId(html: string): string {
  let id = SYM_IDS.get(html)
  if (id === undefined) {
    id = `sym${symSeq++}`
    SYM_IDS.set(html, id)
    symAdopt(id, html)
  }
  return id
}

export function symHref(html: string): string {
  if (symAcc === undefined) {
    const host = document.createElement('div')
    host.setAttribute('aria-hidden', 'true')
    host.style.cssText = 'position:absolute;width:0;height:0;overflow:hidden'
    const svg = document.createElementNS(SVG_NS, 'svg')
    symAcc = document.createElementNS(SVG_NS, 'g')
    svg.appendChild(symAcc)
    host.appendChild(svg)
    document.body.appendChild(host)
    SYM_QUEUE.forEach(e => symAdopt(e.id, e.html))
    SYM_QUEUE.length = 0
  }
  return `#${symId(html)}`
}

