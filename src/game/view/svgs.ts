export function meterInner(filled: number, token: 'dirt' | 'leaf'): string {
  const color = token === 'dirt' ? '#8a5a32' : '#6bc04a'
  let raw = UI_METER
  for (let i = 0; i < filled; i++) {
    raw = raw.replace(`id="fill-${i}" fill="#cfc6b0"`, `id="fill-${i}" fill="${color}"`)
  }
  return svgInner(raw)
}
