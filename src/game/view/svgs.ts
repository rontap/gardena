export function fruitInner(crop: CropId): string {
  return stageOnly(FRUIT[crop], 'common')
}

export function skillInner(id: SkillId): string {
  if (
    id === 'better-carrot' ||
    id === 'better-potato' ||
    id === 'better-wheat' ||
    id === 'better-tomato' ||
    id === 'better-raspberry' ||
    id === 'better-watermelon'
  ) {
    const crop =
      id === 'better-carrot'
        ? 'carrot'
        : id === 'better-potato'
          ? 'potato'
          : id === 'better-wheat'
            ? 'wheat'
            : id === 'better-tomato'
              ? 'tomato'
              : id === 'better-raspberry'
                ? 'raspberry'
                : 'watermelon'
    return `${fruitInner(crop)}${inner(skillBetter)}`
  }
  return SKILL_ART[id]
}
